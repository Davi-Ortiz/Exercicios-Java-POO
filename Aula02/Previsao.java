public class Previsao {
    public static void main(String[] args) {

        System.out.println(7 / 2);          // resultado: 3, pois é uma divisão inteira
        System.out.println(7 / 2.0);        // resultado: 3.5, pois é uma divisão de ponto flutuante
        System.out.println(7.0 / 2);        // resultado: 3.5, pois é uma divisão de ponto flutuante
        System.out.println(7 % 2);          // resultado: 1, pois é o resto da divisão inteira  
        System.out.println((int) 7.9);      // resultado: 7, pois é uma conversão de tipo (casting)
        System.out.println(10 / 4 * 4);     // resultado: 10, pois é uma divisão inteira seguida de multiplicação

    }
}
